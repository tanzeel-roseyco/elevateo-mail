import { beforeEach, expect, it, vi } from 'vitest'
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { ResendConnection } from './ResendConnection'
import { ApiFailure } from '@/data/http/httpClient'

const api = vi.hoisted(() => ({ status: vi.fn(), list: vi.fn(), create: vi.fn(), replace: vi.fn(), revoke: vi.fn(), admit: vi.fn() }))
const state = vi.hoisted(() => ({ accountId: 'alice', recheck: vi.fn(), refresh: vi.fn(), confirm: vi.fn() }))
vi.mock('@/data/http/resendGateway', () => ({ createResendGateway: () => api }))
vi.mock('@/ui/confirm', () => ({ confirm: state.confirm }))
vi.mock('@/data/http/instance', () => ({ http: {},
  useLive: (selector: (value: { accountId: string }) => unknown) => selector({ accountId: state.accountId }),
  live: { store: { getState: () => ({ accountId: state.accountId }) }, recheckSession: state.recheck, refreshMailboxes: state.refresh },
}))
const row = { id: 'alice-key', revision: 2, revoked: 0 }
beforeEach(() => {
  vi.clearAllMocks(); state.accountId = 'alice'; state.confirm.mockResolvedValue(true)
  api.status.mockResolvedValue({ enabled: true }); api.list.mockResolvedValue({ connections: [row] })
  api.create.mockResolvedValue(row); api.replace.mockResolvedValue(row); api.revoke.mockResolvedValue({ ...row, revoked: 1 })
  api.admit.mockResolvedValue({ id: 'mail', address: 'sender@example.com' })
})
it('allows saved access removal while configuration is disabled, with no key or sender entry', async () => {
  api.status.mockResolvedValue({ enabled: false }); render(<ResendConnection />)
  await screen.findByText(/Resend is disabled/u)
  expect(screen.queryByLabelText('Resend API key')).not.toBeInTheDocument()
  expect(api.list).toHaveBeenCalledOnce()
  fireEvent.change(screen.getByLabelText('Connection to manage'), { target: { value: row.id } })
  expect(screen.queryByLabelText('Sender address')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Remove Resend access' }))
  await waitFor(() => expect(api.revoke).toHaveBeenCalledWith(row.id, 2))
  expect(api.create).not.toHaveBeenCalled(); expect(api.replace).not.toHaveBeenCalled(); expect(api.admit).not.toHaveBeenCalled()
})
it('retains metadata and removal when the availability check fails safely', async () => {
  api.status.mockRejectedValue(new Error('private configuration detail'))
  render(<ResendConnection />)
  await screen.findByText(/Resend is disabled/u)
  expect(screen.getByText(/alice-key —/u)).toBeInTheDocument()
  expect(screen.queryByText(/private configuration detail/u)).not.toBeInTheDocument()
  expect(screen.queryByLabelText('Resend API key')).not.toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Connection to manage'), { target: { value: row.id } })
  fireEvent.click(screen.getByRole('button', { name: 'Remove Resend access' }))
  await waitFor(() => expect(api.revoke).toHaveBeenCalledWith(row.id, 2))
})
it('clears listed metadata when the later status check rejects the session', async () => {
  api.status.mockRejectedValue(new ApiFailure('unauthorized', 'Session ended'))
  render(<ResendConnection />)
  await waitFor(() => expect(state.recheck).toHaveBeenCalledOnce())
  expect(screen.queryByText(/alice-key —/u)).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Remove Resend access' })).not.toBeInTheDocument()
})
it('clears the password immediately on submission and refreshes metadata', async () => {
  let resolve!: (value: unknown) => void
  api.create.mockImplementationOnce(() => new Promise(done => { resolve = done }))
  render(<ResendConnection />)
  const input = await screen.findByLabelText('Resend API key')
  await waitFor(() => expect(screen.getByRole('button', { name: 'Store key' })).toBeEnabled())
  fireEvent.change(input, { target: { value: 'synthetic-secret' } })
  fireEvent.submit(input.closest('form')!)
  expect(input).toHaveValue(''); expect(api.create).toHaveBeenCalledWith('synthetic-secret')
  await act(async () => resolve(row))
  expect(await screen.findByText(/Key stored/u)).toBeInTheDocument()
  expect(state.refresh).toHaveBeenCalledOnce()
})
it('replaces by revision, verifies a sender, and confirms revocation', async () => {
  render(<ResendConnection />)
  const select = await screen.findByLabelText('Connection to manage')
  await waitFor(() => expect(select).toBeEnabled())
  fireEvent.change(select, { target: { value: row.id } })
  fireEvent.change(screen.getByLabelText('Sender address'), { target: { value: 'sender@example.com' } })
  fireEvent.change(screen.getByLabelText('Resend domain ID'), { target: { value: 'domain' } })
  fireEvent.submit(screen.getByLabelText('Sender address').closest('form')!)
  await screen.findByText('Verified sender@example.com. Sending remains disabled.')
  expect(api.admit).toHaveBeenCalledWith(row.id, 'sender@example.com', 'domain')
  fireEvent.change(screen.getByLabelText('Resend API key'), { target: { value: 'replacement' } })
  fireEvent.submit(screen.getByLabelText('Resend API key').closest('form')!)
  await screen.findByText(/Key stored/u)
  expect(api.replace).toHaveBeenCalledWith(row.id, 2, 'replacement')
  fireEvent.change(select, { target: { value: row.id } })
  fireEvent.click(screen.getByRole('button', { name: 'Remove Resend access' }))
  await waitFor(() => expect(api.revoke).toHaveBeenCalledWith(row.id, 2))
  expect(state.confirm).toHaveBeenCalledOnce()
})
it('clears metadata on authorization failure and offers safe reload after errors', async () => {
  api.list.mockRejectedValueOnce(new Error('secret must not appear'))
  render(<ResendConnection />)
  await screen.findByRole('alert')
  expect(screen.queryByText(/secret must not appear/u)).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Reload Resend connections' }))
  const select = await screen.findByLabelText('Connection to manage')
  await waitFor(() => expect(select).toBeEnabled())
  fireEvent.change(select, { target: { value: row.id } })
  api.revoke.mockRejectedValueOnce(new ApiFailure('unauthorized', 'Session ended'))
  fireEvent.click(screen.getByRole('button', { name: 'Remove Resend access' }))
  await waitFor(() => expect(state.recheck).toHaveBeenCalledOnce())
  expect(screen.queryByText(/alice-key —/u)).not.toBeInTheDocument()
})
it('clears a key on account change and ignores an old pending mutation result', async () => {
  let resolve!: (value: unknown) => void
  api.create.mockImplementationOnce(() => new Promise(done => { resolve = done }))
  const view = render(<ResendConnection />)
  const input = await screen.findByLabelText('Resend API key')
  await waitFor(() => expect(input).toBeEnabled())
  fireEvent.change(input, { target: { value: 'synthetic-secret' } }); fireEvent.submit(input.closest('form')!)
  state.accountId = 'bob'; api.list.mockResolvedValue({ connections: [] }); view.rerender(<ResendConnection />)
  await screen.findByText('No stored Resend connections.')
  await act(async () => resolve(row))
  expect(state.refresh).not.toHaveBeenCalled()
  expect(screen.queryByText(/Key stored/u)).not.toBeInTheDocument()
  expect(await screen.findByLabelText('Resend API key')).toHaveValue('')
})
