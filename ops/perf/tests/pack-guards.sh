#!/bin/sh
# AIDEV-NOTE: PERF-01 guard-suite payload packer. Runs on the workstation, uses no Docker. It builds the minimal
# allowlisted tree that the four Docker-free guard suites (pack-modes-guards.sh, fleet-guards-guards.sh,
# run-baseline-guards.sh, cleanup-guards.sh) and the scripts they drive actually open, hashes every file into PAYLOAD.sha256, records provenance into PAYLOAD.meta, and writes ONE
# tar meant to be reproducible: ustar format, fixed mtime, owner 0:0 numeric, `--mode=u=rw,go=r,a+X` intended to
# normalize modes to 0644 files / 0755 directories, names pre-sorted bytewise, no recursion. Nothing time-dependent
# enters the archive (the pack timestamp and the git porcelain status go to the PACK.info sidecar next to it). The
# mode normalization and the two-pack identity are ASSERTED by ops/perf/tests/pack-modes-guards.sh (Docker-only, run
# first by fleet-guards.sh against the TAR_FLAGS line below) and have not yet been demonstrated anywhere. The member
# set is read from the MEMBERS block in fleet-guards.sh and must equal this allowlist plus `scripts/` and the two
# PAYLOAD files, so packer and runner cannot drift.
# Allowlist rationale (grep of both suites plus run-baseline.sh, preflight.sh, sample.sh, cleanup.sh, lib.sh):
#   both suites copy `compose.yaml apps/server ops scripts` per case (excluding ops/local and evidence) and read
#   ops/perf/tests/fakebin/*, ops/perf/sample.sh, ops/perf/run-baseline.sh, ops/perf/compose.perf.yaml,
#   ops/tests/db-fixtures.sql; lib.sh names compose.yaml, ops/perf/compose.perf.yaml, ops/local/.env (generated by
#   the suite); preflight.sh reads compose.yaml and apps/server/Dockerfile; run-baseline.sh reads
#   ops/tests/db-fixtures.sql, ops/perf/sql/*.sql, ops/compose.secrets.yaml, ops/perf/sample.sh, ops/perf/preflight.sh
#   and hashes apps/server/Gemfile, Gemfile.lock, Dockerfile, compose.yaml, compose.perf.yaml, load.rb.
#   Nothing under scripts/ and no other ops/tests file is opened, so `scripts` is included only as an EMPTY directory
#   entry (the suites' tar copy names it). ops/perf/transfer.sh (workstation ssh helper) is not opened by anything and
#   is left out. Nothing from ops/local, evidence/, .git or docs enters the payload.
# Usage: sh ops/perf/tests/pack-guards.sh <output dir>   (created exclusively, must lie outside the repository)
# Prints the archive SHA-256 and the manifest SHA-256. Exit: 0 packed and verified; 2 usage or refusal (output dir
# exists or lies inside the repo, missing or non-regular allowlisted file, CR byte in a payload file, non-GNU tar);
# 4 a packing step failed (hash, provenance, tar, archive verification).
set -eu
die() { echo "pack-guards: $1" >&2; exit "${2-2}"; }

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd -P)
OUT=${1-}
[ -n "$OUT" ] || die "usage: pack-guards.sh <output dir>"
[ ! -e "$OUT" ] || die "output dir exists ($OUT); nothing written"
PARENT=$(CDPATH= cd -- "$(dirname -- "$OUT")" 2>/dev/null && pwd -P) || die "parent of output dir does not exist"
case "$PARENT/" in "$ROOT/"*) die "output dir must lie outside the repository ($ROOT)" ;; esac
tv=$(tar --version 2>/dev/null) || die "tar not found"
case "$tv" in *"GNU tar"*) ;; *) die "GNU tar required (--mtime/--owner/--numeric-owner/--mode/--no-recursion)" ;; esac
command -v sha256sum >/dev/null 2>&1 || die "sha256sum not found"
command -v git >/dev/null 2>&1 || die "git not found"

mkdir "$OUT" || die "cannot create output dir ($OUT)"
OUT=$(CDPATH= cd -- "$OUT" && pwd -P)
LIST="$OUT/payload-files.list"       # regular files, bytewise sorted
TARLIST="$OUT/payload-members.list"  # files plus the one empty directory entry, bytewise sorted
TAR_MTIME='@1767225600'              # 2026-01-01T00:00:00Z, fixed for every member
# The exact tar flag string; pack-modes-guards.sh greps this one line and exercises the same flags. Keep it one line,
# no shell quoting inside, unchanged mtime unless the suite is updated too.
TAR_FLAGS="--format=ustar --no-recursion --mtime=@1767225600 --owner=0 --group=0 --numeric-owner --mode=u=rw,go=r,a+X"

cat > "$LIST" <<'EOF'
apps/server/Dockerfile
apps/server/Gemfile
apps/server/Gemfile.lock
compose.yaml
ops/compose.secrets.yaml
ops/perf/cleanup.sh
ops/perf/compose.perf.yaml
ops/perf/lib.sh
ops/perf/load.rb
ops/perf/preflight.sh
ops/perf/run-baseline.sh
ops/perf/sample.sh
ops/perf/sql/explain-rls.sql
ops/perf/tests/cleanup-guards.sh
ops/perf/tests/fakebin/date
ops/perf/tests/fakebin/docker
ops/perf/tests/fleet-guards-guards.sh
ops/perf/tests/fleet-guards.sh
ops/perf/tests/pack-guards.sh
ops/perf/tests/pack-modes-guards.sh
ops/perf/tests/run-baseline-guards.sh
ops/tests/db-fixtures.sql
EOF
LC_ALL=C sort -o "$LIST" "$LIST"
EMPTY_DIRS='scripts'

# --- The runner's embedded member list must be exactly this allowlist + the empty dirs + the two PAYLOAD files. ---
RUNNER="$ROOT/ops/perf/tests/fleet-guards.sh"
[ -f "$RUNNER" ] || die "fleet-guards.sh missing; the member list is read from it"
awk '/^MEMBERS$/ { f = 0 } f { print } /<<.MEMBERS.$/ { f = 1 }' "$RUNNER" > "$OUT/runner-members.list" || die "reading the MEMBERS block failed"
[ -s "$OUT/runner-members.list" ] || die "no MEMBERS block found in fleet-guards.sh"
{ cat "$LIST"; for d in $EMPTY_DIRS; do echo "$d/"; done; echo PAYLOAD.sha256; echo PAYLOAD.meta; } > "$OUT/expected-members.list"
LC_ALL=C sort -o "$OUT/expected-members.list" "$OUT/expected-members.list"
LC_ALL=C sort -o "$OUT/runner-members.list" "$OUT/runner-members.list"
cmp -s "$OUT/expected-members.list" "$OUT/runner-members.list" || die "allowlist differs from the MEMBERS block in fleet-guards.sh (see expected-members.list vs runner-members.list); fix one of them"

# --- Every allowlisted path must be a regular, non-symlink, LF-only file; fail closed on anything else. ---
while IFS= read -r f; do
  case "$f" in ops/local/*|evidence/*|.git/*|docs/*) die "allowlist names an excluded area: $f" ;; esac
  [ ! -L "$ROOT/$f" ] || die "allowlisted path is a symlink: $f"
  [ -f "$ROOT/$f" ] || die "allowlisted file missing or not a regular file: $f"
  crs=$(tr -cd '\r' < "$ROOT/$f" | wc -c | tr -d ' ')
  [ "$crs" -eq 0 ] || die "CR bytes in $f ($crs); the suites run under a Linux sh, pack only LF files"
done < "$LIST"
for d in $EMPTY_DIRS; do [ -d "$ROOT/$d" ] || die "directory missing: $d"; done

# --- PAYLOAD.sha256: one checked sha256sum call per file (no pipeline), binary marker for host-independent lines. ---
: > "$OUT/PAYLOAD.sha256"
n=0
while IFS= read -r f; do
  ( cd "$ROOT" && sha256sum -b -- "$f" ) >> "$OUT/PAYLOAD.sha256" || die "hashing $f failed" 4
  n=$((n + 1))
done < "$LIST"
[ "$(wc -l < "$OUT/PAYLOAD.sha256" | tr -d ' ')" -eq "$n" ] || die "manifest has a different line count than the allowlist" 4

# --- PAYLOAD.meta: provenance that is a function of the tree, nothing time-dependent. No clean commit is required;
#     HEAD and the hash of the dirty diff over the allowlisted paths go inside the archive; the pack time and the
#     porcelain status (which also names untracked allowlisted files, invisible to `git diff`) go to PACK.info. ---
HEAD=$(git -C "$ROOT" rev-parse HEAD) || die "git rev-parse HEAD failed" 4
# shellcheck disable=SC2046
git -C "$ROOT" diff HEAD -- $(cat "$LIST") > "$OUT/dirty.diff" || die "git diff failed" 4
# shellcheck disable=SC2046
git -C "$ROOT" status --porcelain --untracked-files=all -- $(cat "$LIST") > "$OUT/status.porcelain" || die "git status failed" 4
DIRTY_SHA=$(sha256sum -b -- "$OUT/dirty.diff") || die "hashing the dirty diff failed" 4
STATUS_SHA=$(sha256sum -b -- "$OUT/status.porcelain") || die "hashing the status failed" 4
{
  echo "packer=ops/perf/tests/pack-guards.sh"
  echo "git_head=$HEAD"
  echo "git_dirty_diff_sha256=${DIRTY_SHA%% *}"
  echo "allowlist_files=$n"
  echo "empty_dirs=$EMPTY_DIRS"
  echo "tar_flags=$TAR_FLAGS"
} > "$OUT/PAYLOAD.meta" || die "writing PAYLOAD.meta failed" 4
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
{
  echo "packed_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "git_head=$HEAD"
  echo "git_dirty_diff_sha256=${DIRTY_SHA%% *}"
  echo "git_dirty_diff_bytes=$(wc -c < "$OUT/dirty.diff" | tr -d ' ')"
  echo "git_status_porcelain_sha256=${STATUS_SHA%% *}"
  echo "git_status_porcelain_lines=$(wc -l < "$OUT/status.porcelain" | tr -d ' ')"
  echo "--- git status --porcelain --untracked-files=all (allowlisted paths) ---"
  cat "$OUT/status.porcelain"
} > "$OUT/PACK.info" || die "writing PACK.info failed" 4

# --- The archive: members from the pre-sorted list, no recursion, fixed metadata; PAYLOAD.* appended from OUT. ---
{ cat "$LIST"; for d in $EMPTY_DIRS; do echo "$d"; done; } > "$TARLIST"
LC_ALL=C sort -o "$TARLIST" "$TARLIST"
ARCHIVE="$OUT/perf01-guards-payload-$STAMP.tar"
# shellcheck disable=SC2086
tar $TAR_FLAGS -cf "$ARCHIVE" -C "$ROOT" -T "$TARLIST" -C "$OUT" PAYLOAD.sha256 PAYLOAD.meta || die "tar failed" 4

# --- Verify the member list is exactly the allowlist + empty dirs + the two PAYLOAD files, nothing else. ---
tar -tf "$ARCHIVE" > "$OUT/archive-members.list" || die "listing the archive failed" 4
LC_ALL=C sort -o "$OUT/archive-members.list" "$OUT/archive-members.list"
cmp -s "$OUT/expected-members.list" "$OUT/archive-members.list" || die "archive members differ from the allowlist (see expected-members.list vs archive-members.list)" 4

ARCHIVE_SHA=$(sha256sum -b -- "$ARCHIVE") || die "hashing the archive failed" 4
MANIFEST_SHA=$(sha256sum -b -- "$OUT/PAYLOAD.sha256") || die "hashing the manifest failed" 4
printf '%s  %s\n' "${ARCHIVE_SHA%% *}" "$(basename -- "$ARCHIVE")" > "$OUT/ARCHIVE.sha256"
echo "payload archive : $ARCHIVE"
echo "archive sha256  : ${ARCHIVE_SHA%% *}"
echo "manifest sha256 : ${MANIFEST_SHA%% *}  (PAYLOAD.sha256, $n files)"
echo "git head        : $HEAD  dirty-diff sha256 ${DIRTY_SHA%% *}  (pack time and porcelain status in PACK.info, outside the archive)"
echo "hand the archive sha256 to the coordinator separately from the .tar; fleet-guards.sh takes it as its second argument"
echo "and refuses to let tar read the archive unless it matches, then validates members, extracts and checks PAYLOAD.sha256."
